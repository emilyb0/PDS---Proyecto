-- ================================================ Reglas que cruzan tablas

-- Reserva: roles de quien crea y de quien responde; dispositivo activo;
-- grabación de eventos solo con drones; código de entrega solo (y siempre) en robots.
CREATE FUNCTION fn_validar_reserva() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_tipo tipo_dispositivo;
  v_baja DATE;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM usuario WHERE id_usuario = NEW.id_administrador
                   AND rol = 'ADMINISTRADOR' AND estado = 'ACTIVO') THEN
    RAISE EXCEPTION 'La reserva debe crearla un administrador activo (RF05)';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM usuario WHERE id_usuario = NEW.id_operador
                   AND rol = 'OPERADOR' AND estado = 'ACTIVO') THEN
    RAISE EXCEPTION 'El responsable de la reserva debe ser un operador activo (RF05)';
  END IF;

  SELECT tipo, fecha_baja INTO v_tipo, v_baja
    FROM dispositivo WHERE id_dispositivo = NEW.id_dispositivo;
  IF v_baja IS NOT NULL THEN
    RAISE EXCEPTION 'El dispositivo % está dado de baja', NEW.id_dispositivo;
  END IF;
  IF NEW.tipo_servicio = 'GRABACION_EVENTO' AND v_tipo <> 'DRONE' THEN
    RAISE EXCEPTION 'La grabación de eventos solo se asigna a drones';
  END IF;
  IF (v_tipo = 'ROBOT') <> (NEW.codigo_entrega IS NOT NULL) THEN
    RAISE EXCEPTION 'El código de entrega es obligatorio en robots y no aplica a drones (RF24)';
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_reserva_validar
  BEFORE INSERT OR UPDATE OF id_administrador, id_operador, id_dispositivo,
                             tipo_servicio, codigo_entrega
  ON reserva FOR EACH ROW EXECUTE FUNCTION fn_validar_reserva();

-- Dispositivo: solo se da de baja si no tiene reservas pendientes (RF03).
CREATE FUNCTION fn_validar_baja() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.fecha_baja IS NOT NULL AND OLD.fecha_baja IS NULL AND EXISTS (
       SELECT 1 FROM reserva
        WHERE id_dispositivo = NEW.id_dispositivo
          AND estado IN ('PROGRAMADA', 'EN_CURSO')) THEN
    RAISE EXCEPTION 'El dispositivo % tiene reservas pendientes y no se puede dar de baja (RF03)',
                    NEW.id_dispositivo;
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER trg_dispositivo_baja
  BEFORE UPDATE OF fecha_baja ON dispositivo
  FOR EACH ROW EXECUTE FUNCTION fn_validar_baja();

-- ============================================================== Reportes

-- RF17: servicios, horas de uso e incidencias de un dispositivo en un rango de fechas.
CREATE FUNCTION reporte_dispositivo(p_dispositivo INT, p_desde DATE, p_hasta DATE)
RETURNS TABLE (numero_servicios BIGINT, horas_uso NUMERIC, numero_incidencias BIGINT)
LANGUAGE sql STABLE AS $$
  WITH s AS (
    SELECT b.id_bitacora, b.hora_salida, b.hora_regreso
      FROM bitacora_servicio b
      JOIN reserva r ON r.id_reserva = b.id_reserva
     WHERE r.id_dispositivo = p_dispositivo
       AND b.hora_salida >= p_desde
       AND b.hora_salida <  p_hasta + 1
  )
  SELECT (SELECT count(*) FROM s),
         (SELECT coalesce(round(sum(extract(epoch FROM hora_regreso - hora_salida)) / 3600, 2), 0)
            FROM s WHERE hora_regreso IS NOT NULL),
         (SELECT count(*) FROM incidencia i JOIN s ON s.id_bitacora = i.id_bitacora);
$$;
