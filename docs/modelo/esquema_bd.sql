-- =====================================================================
--  Sistema centralizado de robots y drones
--  Esquema de base de datos — PostgreSQL 16
--  Derivado del diagrama de clases.
--  Trazabilidad: RF01–RF27, RNF01, RNF05, RNF09, RESTR01, RESTR04
--
--  Decisiones de mapeo:
--   * Usuario/Administrador/Operador  -> una tabla (usuario.rol).
--   * Dispositivo/Robot/Drone         -> una tabla (dispositivo.tipo) con
--                                        columnas de subtipo validadas por CHECK.
--   * Alerta/AlertaServicio/AlertaMantenimiento -> tabla por subclase (PK = FK).
--   * Ubicacion (dataType): catálogo "ubicacion" para origen/destino; columnas
--     latitud/longitud embebidas en telemetría e incidencia.
--   * Map<String, EstadoSensor> de la telemetría -> tabla lectura_sensor.
--   * ReporteDispositivo no se guarda: lo calcula reporte_dispositivo().
--   * Pronostico (API de clima) no se guarda.
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;   -- necesaria para la restricción de cruce (RF06)

-- ------------------------------------------------------------------ Tipos
CREATE TYPE rol_usuario        AS ENUM ('ADMINISTRADOR', 'OPERADOR');
CREATE TYPE estado_usuario     AS ENUM ('ACTIVO', 'INACTIVO');
CREATE TYPE accion_auditoria   AS ENUM ('CREAR', 'EDITAR', 'BAJA');
CREATE TYPE tipo_dispositivo   AS ENUM ('ROBOT', 'DRONE');
CREATE TYPE estado_dispositivo AS ENUM ('DISPONIBLE', 'EN_SERVICIO', 'EN_CARGA',
                                        'EN_MANTENIMIENTO', 'FUERA_DE_SERVICIO');
CREATE TYPE estado_sensor      AS ENUM ('OK', 'FALLA');
CREATE TYPE tipo_mantenimiento AS ENUM ('PREVENTIVO', 'CORRECTIVO');
CREATE TYPE tipo_servicio      AS ENUM ('ENTREGA_DOCUMENTOS', 'PEDIDO_CAFETERIA', 'GRABACION_EVENTO');
CREATE TYPE estado_reserva     AS ENUM ('PROGRAMADA', 'EN_CURSO', 'FINALIZADA', 'CANCELADA');
CREATE TYPE estado_servicio    AS ENUM ('EN_CURSO', 'ENTREGADO', 'RETORNANDO', 'FINALIZADO');
CREATE TYPE tipo_incidencia    AS ENUM ('BATERIA_BAJA', 'SENSOR_EN_FALLA', 'RETRASO', 'SALIDA_DE_ZONA',
                                        'ORDEN_RETORNO', 'PARADA_EMERGENCIA', 'ENTREGA_NO_CONFIRMADA');
CREATE TYPE tipo_alerta        AS ENUM ('SERVICIO', 'MANTENIMIENTO');
CREATE TYPE causa_alerta       AS ENUM ('BATERIA_BAJA', 'SENSOR_EN_FALLA', 'RETRASO', 'SALIDA_DE_ZONA');

-- ======================================================= Usuarios y seguridad

CREATE TABLE usuario (
  id_usuario            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre                VARCHAR(100)   NOT NULL,
  correo_institucional  VARCHAR(120)   NOT NULL,
  contrasena_hash       VARCHAR(255)   NOT NULL,          -- bcrypt/argon2, nunca texto plano (RNF05)
  rol                   rol_usuario    NOT NULL,          -- RF18
  estado                estado_usuario NOT NULL DEFAULT 'ACTIVO',   -- RF19
  fecha_creacion        TIMESTAMP      NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_usuario_correo ON usuario (lower(correo_institucional));   -- RF20

CREATE TABLE registro_auditoria (                       -- RNF09
  id_auditoria  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario    INT              NOT NULL REFERENCES usuario (id_usuario),
  fecha_hora    TIMESTAMP        NOT NULL DEFAULT now(),
  accion        accion_auditoria NOT NULL,
  entidad       VARCHAR(50)      NOT NULL,                -- tabla afectada
  id_entidad    INT              NOT NULL                 -- id del registro afectado
);
CREATE INDEX ix_auditoria_usuario_fecha ON registro_auditoria (id_usuario, fecha_hora);

-- ================================================= Inventario de dispositivos

CREATE TABLE dispositivo (                              -- RF01–RF04, RNF10
  id_dispositivo        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo                  tipo_dispositivo   NOT NULL,      -- discriminador Robot/Drone
  numero_serie          VARCHAR(50)        NOT NULL UNIQUE,
  modelo                VARCHAR(80)        NOT NULL,
  estado                estado_dispositivo NOT NULL DEFAULT 'DISPONIBLE',
  nivel_bateria         SMALLINT           NOT NULL DEFAULT 100,
  horas_uso_desde_mant  NUMERIC(7,2)       NOT NULL DEFAULT 0,    -- RF16
  capacidad_carga_kg    NUMERIC(6,2),                     -- solo ROBOT
  autonomia_vuelo_min   SMALLINT,                         -- solo DRONE
  fecha_registro        DATE               NOT NULL DEFAULT current_date,
  fecha_baja            DATE,                             -- RF03
  motivo_baja           VARCHAR(255),
  CONSTRAINT ck_disp_bateria  CHECK (nivel_bateria BETWEEN 0 AND 100),
  CONSTRAINT ck_disp_horas    CHECK (horas_uso_desde_mant >= 0),
  CONSTRAINT ck_disp_carga    CHECK (capacidad_carga_kg > 0),
  CONSTRAINT ck_disp_vuelo    CHECK (autonomia_vuelo_min > 0),
  CONSTRAINT ck_disp_subtipo  CHECK (
       (tipo = 'ROBOT' AND capacidad_carga_kg  IS NOT NULL AND autonomia_vuelo_min IS NULL)
    OR (tipo = 'DRONE' AND autonomia_vuelo_min IS NOT NULL AND capacidad_carga_kg  IS NULL)),
  CONSTRAINT ck_disp_baja     CHECK ((fecha_baja IS NULL) = (motivo_baja IS NULL))
);
CREATE INDEX ix_dispositivo_tipo_estado ON dispositivo (tipo, estado);    -- filtros de RF04

CREATE TABLE sensor (
  id_sensor       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_dispositivo  INT           NOT NULL REFERENCES dispositivo (id_dispositivo) ON DELETE CASCADE,
  nombre          VARCHAR(60)   NOT NULL,
  estado          estado_sensor NOT NULL DEFAULT 'OK',    -- RF07
  CONSTRAINT uq_sensor_nombre UNIQUE (id_dispositivo, nombre)
);

CREATE TABLE mantenimiento (                            -- RF15, RF16
  id_mantenimiento  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_dispositivo    INT                NOT NULL REFERENCES dispositivo (id_dispositivo),
  id_operador       INT                NOT NULL REFERENCES usuario (id_usuario),   -- responsable
  tipo              tipo_mantenimiento NOT NULL,
  descripcion       TEXT               NOT NULL,
  fecha_inicio      DATE               NOT NULL,
  fecha_fin         DATE,                               -- NULL mientras dura
  CONSTRAINT ck_mant_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);
CREATE INDEX ix_mant_dispositivo ON mantenimiento (id_dispositivo, fecha_fin);

-- ============================================ Reservas, bitácora y monitoreo

CREATE TABLE ubicacion (                                -- puntos del campus (origen / destino)
  id_ubicacion  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre        VARCHAR(80)  NOT NULL UNIQUE,
  latitud       NUMERIC(9,6) NOT NULL CHECK (latitud  BETWEEN  -90 AND  90),
  longitud      NUMERIC(9,6) NOT NULL CHECK (longitud BETWEEN -180 AND 180)
);

CREATE TABLE zona_operacion (                           -- RF25
  id_zona  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre   VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE vertice_zona (                             -- polígono de la zona, en orden
  id_zona   INT          NOT NULL REFERENCES zona_operacion (id_zona) ON DELETE CASCADE,
  orden     SMALLINT     NOT NULL CHECK (orden >= 1),
  latitud   NUMERIC(9,6) NOT NULL,
  longitud  NUMERIC(9,6) NOT NULL,
  PRIMARY KEY (id_zona, orden)
);

CREATE TABLE reserva (                                  -- RF05, RF06, RF21, RF22, RF24
  id_reserva             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_administrador       INT            NOT NULL REFERENCES usuario (id_usuario),     -- quien la crea
  id_operador            INT            NOT NULL REFERENCES usuario (id_usuario),     -- responsable
  id_dispositivo         INT            NOT NULL REFERENCES dispositivo (id_dispositivo),
  id_origen              INT            NOT NULL REFERENCES ubicacion (id_ubicacion),
  id_destino             INT            NOT NULL REFERENCES ubicacion (id_ubicacion),
  tipo_servicio          tipo_servicio  NOT NULL,
  fecha                  DATE           NOT NULL,
  hora_inicio            TIME           NOT NULL,
  duracion_estimada_min  SMALLINT       NOT NULL CHECK (duracion_estimada_min > 0),
  horario                TSRANGE GENERATED ALWAYS AS (
                           tsrange(fecha + hora_inicio,
                                   fecha + hora_inicio + duracion_estimada_min * INTERVAL '1 minute')
                         ) STORED NOT NULL,             -- [inicio, fin) calculado
  estado                 estado_reserva NOT NULL DEFAULT 'PROGRAMADA',
  codigo_entrega         CHAR(4)        CHECK (codigo_entrega ~ '^[0-9]{4}$'),   -- solo robots
  motivo_cambio          VARCHAR(255),                  -- RF21
  fecha_creacion         TIMESTAMP      NOT NULL DEFAULT now(),
  CONSTRAINT ck_reserva_motivo CHECK (estado <> 'CANCELADA' OR motivo_cambio IS NOT NULL),
  -- RF06 / RF21: un dispositivo no puede tener dos reservas activas cuyos horarios se crucen.
  -- Las canceladas o finalizadas no cuentan, así que cancelar libera el horario.
  CONSTRAINT ex_reserva_cruce EXCLUDE USING gist (id_dispositivo WITH =, horario WITH &&)
    WHERE (estado IN ('PROGRAMADA', 'EN_CURSO'))
);
CREATE INDEX ix_reserva_fecha ON reserva (fecha);

CREATE TABLE bitacora_servicio (                        -- RF08
  id_bitacora   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reserva    INT             NOT NULL UNIQUE REFERENCES reserva (id_reserva),   -- 1 : 0..1
  hora_salida   TIMESTAMP       NOT NULL,
  hora_regreso  TIMESTAMP,
  hora_entrega  TIMESTAMP,                              -- RF24
  estado        estado_servicio NOT NULL DEFAULT 'EN_CURSO',
  CONSTRAINT ck_bit_regreso  CHECK (hora_regreso IS NULL OR hora_regreso >= hora_salida),
  CONSTRAINT ck_bit_entrega  CHECK (hora_entrega IS NULL OR hora_entrega >= hora_salida),
  CONSTRAINT ck_bit_entregado CHECK (estado <> 'ENTREGADO' OR hora_entrega IS NOT NULL),
  CONSTRAINT ck_bit_cierre   CHECK ((estado = 'FINALIZADO') = (hora_regreso IS NOT NULL))
);

CREATE TABLE registro_telemetria (                      -- RF09, RF10 (ruta recorrida)
  id_telemetria    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_bitacora      INT          NOT NULL REFERENCES bitacora_servicio (id_bitacora) ON DELETE CASCADE,
  fecha_hora       TIMESTAMP    NOT NULL,
  latitud          NUMERIC(9,6) NOT NULL,
  longitud         NUMERIC(9,6) NOT NULL,
  nivel_bateria    SMALLINT     NOT NULL CHECK (nivel_bateria BETWEEN 0 AND 100),
  estado_servicio  VARCHAR(40)  NOT NULL,               -- tal como lo reporta la API del dispositivo
  CONSTRAINT uq_telemetria_punto UNIQUE (id_bitacora, fecha_hora)
);

CREATE TABLE lectura_sensor (                           -- estado de cada sensor en cada punto
  id_telemetria  BIGINT        NOT NULL REFERENCES registro_telemetria (id_telemetria) ON DELETE CASCADE,
  id_sensor      INT           NOT NULL REFERENCES sensor (id_sensor),
  estado         estado_sensor NOT NULL,
  PRIMARY KEY (id_telemetria, id_sensor)
);

CREATE TABLE incidencia (                               -- RF08, RF14, RF24, RF25
  id_incidencia  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_bitacora    INT             NOT NULL REFERENCES bitacora_servicio (id_bitacora) ON DELETE CASCADE,
  fecha_hora     TIMESTAMP       NOT NULL DEFAULT now(),
  tipo           tipo_incidencia NOT NULL,
  descripcion    TEXT            NOT NULL,
  latitud        NUMERIC(9,6),
  longitud       NUMERIC(9,6),
  CONSTRAINT ck_inc_ubicacion CHECK ((latitud IS NULL) = (longitud IS NULL)),
  CONSTRAINT ck_inc_zona      CHECK (tipo <> 'SALIDA_DE_ZONA' OR latitud IS NOT NULL)   -- RF25
);
CREATE INDEX ix_incidencia_bitacora ON incidencia (id_bitacora);

-- ================================================================== Alertas

CREATE TABLE alerta (                                   -- superclase
  id_alerta       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo            tipo_alerta  NOT NULL,                -- discriminador
  id_dispositivo  INT          NOT NULL REFERENCES dispositivo (id_dispositivo),
  fecha_hora      TIMESTAMP    NOT NULL DEFAULT now(),
  descripcion     VARCHAR(255) NOT NULL
);
CREATE INDEX ix_alerta_dispositivo ON alerta (id_dispositivo, fecha_hora);

CREATE TABLE alerta_servicio (                          -- RF11, RF25
  id_alerta      INT          PRIMARY KEY REFERENCES alerta (id_alerta) ON DELETE CASCADE,
  id_incidencia  INT          NOT NULL UNIQUE REFERENCES incidencia (id_incidencia),  -- 1 : 0..1
  causa          causa_alerta NOT NULL
);

CREATE TABLE alerta_mantenimiento (                     -- RF16
  id_alerta           INT          PRIMARY KEY REFERENCES alerta (id_alerta) ON DELETE CASCADE,
  dias_desde_ultimo   SMALLINT     NOT NULL CHECK (dias_desde_ultimo  >= 0),
  horas_desde_ultimo  NUMERIC(7,2) NOT NULL CHECK (horas_desde_ultimo >= 0)
);

CREATE TABLE atencion_alerta (                          -- RF27
  id_atencion     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_alerta       INT          NOT NULL UNIQUE REFERENCES alerta_servicio (id_alerta),  -- solo de servicio
  id_operador     INT          NOT NULL REFERENCES usuario (id_usuario),
  fecha_hora      TIMESTAMP    NOT NULL DEFAULT now(),
  causa_revisada  VARCHAR(255) NOT NULL,
  observaciones   TEXT
);

